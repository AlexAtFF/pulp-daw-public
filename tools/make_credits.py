"""Writes CREDITS.md from factory/manifest.json (every file of the factory library), factory/sources.json
(where the recordings came from and under which licence) and the fixed list of third-party code.
usage: python -I tools/make_credits.py   (run from the project folder, after the factory library is built)"""
import json, os, collections

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
manifest = json.load(open(os.path.join(root, "factory", "manifest.json"), encoding="utf-8"))
files = manifest["files"]
sources_path = os.path.join(root, "factory", "sources.json")
sources = json.load(open(sources_path, encoding="utf-8")) if os.path.exists(sources_path) else {"sources": [], "instruments": [], "not_found": []}

out = []
out.append("# PULP credits and licences\n")
out.append("This file is generated by `tools/make_credits.py` from `factory/manifest.json` and `factory/sources.json`. Do not edit it by hand.\n")
out.append("## PULP itself\n")
out.append("PULP is free software. It contains no Image-Line (FL Studio) code, names, graphics, presets or samples,\n"
           "and is not affiliated with or endorsed by Image-Line. Because it is built on the JUCE framework under\n"
           "JUCE's open-source option, the program as a whole is covered by the GNU Affero General Public License\n"
           "version 3 (AGPLv3); the full text is in `LICENSE`.\n")
out.append("## Third-party code\n")
out.append("| Component | Version | Used for | Licence option that applies |")
out.append("|-----------|---------|----------|------------------------------|")
out.append("| JUCE (juce_core, juce_events, juce_data_structures, juce_graphics, juce_gui_basics, juce_audio_basics, juce_audio_devices, juce_audio_processors) | 9.0.4 | windows, drawing, input, audio and MIDI devices, plugin hosting | AGPLv3 (the open-source side of JUCE's dual licence) |")
out.append("| Steinberg ASIO SDK headers, as bundled inside JUCE's juce_audio_devices | bundled with JUCE 9.0.4 | ASIO driver support | GPLv3 (the SDK is offered under the Steinberg ASIO licence or GPLv3; GPLv3 is the one used) |")
out.append("| Libraries bundled inside JUCE's modules (HarfBuzz, SheenBidi, libpng, libjpeg, zlib and others) | see `JUCE.spdx.json` in the JUCE source | text shaping and image formats | their own permissive licences, listed in JUCE's SPDX file |")
extra = os.path.join(root, "tools", "credits_code.md")       # further rows (for example the VST3 SDK once hosting is built)
if os.path.exists(extra):
    out.append(open(extra, encoding="utf-8").read().rstrip("\n"))
out.append("")
out.append("Build tools (not part of the program): CMake 4.4.4 (BSD 3-Clause), Ninja 1.13.2 (Apache 2.0), Microsoft Visual C++ Build Tools.\n")
out.append("The engine (`engine/`) uses no third-party code at all: its WAV, AIFF, FLAC, Ogg Vorbis and MP3 readers and writers, its time-stretcher,\n"
           "its synthesizers and its effects were written for PULP.\n")

out.append("## Factory library\n")
synth = [f for f in files if f["author"] == "PULP" and "Synthesized" in f["source"]]
recorded = [f for f in files if f["author"] != "PULP"]
out.append("%d files in all. %d were synthesized by PULP's own code (the 808 and 909 drum machines were analogue\n"
           "synthesizers, so those kits are built from oscillators, noise and envelopes; instruments for which no\n"
           "licence-clean recording was found are synthesized too, and say so). They are released under CC0 1.0.\n"
           "%d come from recordings by other people, listed below with their licences; PULP trimmed, looped and\n"
           "mapped them but did not otherwise change the sound.\n" % (len(files), len(synth), len(recorded)))
if sources["sources"]:
    out.append("### Where the recordings come from\n")
    out.append("| Source | Author | Licence | Where the licence is stated | Home |")
    out.append("|--------|--------|---------|------------------------------|------|")
    for s in sources["sources"]:
        quote = s.get("licence_quote", "")
        out.append("| %s | %s | %s | %s%s | %s |" % (s.get("name", ""), s.get("author", ""), s.get("licence", ""), s.get("licence_url", ""),
                                                 (' ("%s")' % quote) if quote else "", s.get("home", "")))
    out.append("")
    attributions = [s.get("attribution", "") for s in sources["sources"] if s.get("attribution")]
    if attributions:
        out.append("Attribution required by the licences above:\n")
        for a in attributions:
            out.append("- " + a)
        out.append("")
    by_name = {s["id"]: s for s in sources["sources"]}
    out.append("### Instruments built from recordings\n")
    out.append("| Instrument | Category | Notes | Source | Licence |")
    out.append("|------------|----------|-------|--------|---------|")
    for inst in sources["instruments"]:
        ids = collections.OrderedDict((f["source"], 1) for f in inst["files"])
        names = ", ".join(by_name[i]["name"] for i in ids if i in by_name)
        lic = ", ".join(sorted(set(by_name[i]["licence"] for i in ids if i in by_name)))
        out.append("| %s | %s | %d | %s | %s |" % (inst["name"], inst.get("category", ""), len(inst["files"]), names, lic))
    out.append("")
    if sources.get("not_found"):
        out.append("No licence-clean recording was found for: " + ", ".join(n["name"] for n in sources["not_found"]) + ".\n")

out.append("### Every file\n")
groups = collections.OrderedDict()
for f in files:
    groups.setdefault(os.path.dirname(f["path"]), []).append(f)
for folder, items in groups.items():
    out.append("#### %s\n" % folder)
    out.append("| File | Author | Source | Licence | SHA-256 |")
    out.append("|------|--------|--------|---------|---------|")
    for f in items:
        src = f["source"] + ((" <" + f["url"] + ">") if f.get("url") else "")
        out.append("| %s | %s | %s | %s | `%s` |" % (os.path.basename(f["path"]), f["author"], src, f["licence"], f["sha256"]))
    out.append("")
open(os.path.join(root, "CREDITS.md"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("wrote CREDITS.md with", len(files), "factory files")
