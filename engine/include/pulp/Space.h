// The phase of a low-frequency oscillator across one quantum.
// While the song plays, the phase is a function of the song position, so an export and playback agree;
// while it is stopped, the oscillator runs free from where it was. A jump (transport moved, sync division
// changed) is not applied at once: the phase slides to its new place over a few milliseconds so that
// nothing clicks. When a free rate in Hz, or the tempo under it, is automated during playback the phase
// stays continuous instead (see LfoClock::begin).
struct LfoClock {
    double phase0 = 0.0, inc = 0.0;         // phase (cycles) at the first sample, and per sample
    double slip0 = 0.0, slipStep = 0.0;     // what is left of a jump, sliding to zero
    double rateHz = 0.0;                    // the rate in force this quantum
    void reset() { primed_ = false; offset_ = 0.0; end_ = 0.0; }
    // freeHz is used when cycleTicks <= 0; otherwise one cycle lasts cycleTicks ticks.
    void begin(const ProcessContext& c, double sr, double freeHz, double cycleTicks);
    inline double at(int i) const { return phase0 + (inc + slipStep) * (double)i + slip0; }   // not wrapped
private:
    bool primed_ = false, wasPlaying_ = false, wasSynced_ = false;
    double end_ = 0.0, offset_ = 0.0, nextTick_ = 0.0, lastCpt_ = 0.0;
};

// Delay line read with third-order Lagrange interpolation, for modulated delays (less high-frequency
// loss than the linear interpolation of dsp::DelayLine, and exact at whole-sample delays).
struct ModDelay {
    std::vector<float> buf;
    int w = 0, mask = 0;
    void prepare(int maxSamples) {
        int n = 1;
        while (n < maxSamples + 8) n <<= 1;
        buf.assign((size_t)n, 0.0f);
        mask = n - 1;
        w = 0;
    }
    void clear() { std::fill(buf.begin(), buf.end(), 0.0f); }
    inline void write(float x) { buf[(size_t)w] = x; w = (w + 1) & mask; }
    inline float tap(int delay) const { return buf[(size_t)((w - 1 - delay) & mask)]; }   // 0 = the last written sample
    // delay >= 1, counted from the last written sample
    inline float tapCubic(float delay) const {
        const int d = (int)delay;
        const float f = delay - (float)d;
        const float ym = buf[(size_t)((w - d) & mask)], y0 = buf[(size_t)((w - 1 - d) & mask)];
        const float y1 = buf[(size_t)((w - 2 - d) & mask)], y2 = buf[(size_t)((w - 3 - d) & mask)];
        const float fm = f - 1.0f, f2 = f - 2.0f, fp = f + 1.0f;
        return ym * (-f * fm * f2 * (1.0f / 6.0f)) + y0 * (fp * fm * f2 * 0.5f)
             + y1 * (-fp * f * f2 * 0.5f) + y2 * (fp * f * fm * (1.0f / 6.0f));
    }
};

