// Dry/wet law of the time-based effects: both at full level in the middle, dry only at 0, wet only at 1.
inline void mixGains(float mix, float& dry, float& wet) {
    dry = mix <= 0.5f ? 1.0f : 2.0f * (1.0f - mix);
    wet = mix >= 0.5f ? 1.0f : 2.0f * mix;
}

// A biquad's state decays for ever; once it is far below anything audible, call it zero (no denormals).
inline void settle(dsp::Biquad& b) {
    if (std::fabs(b.z1) < 1.0e-20) b.z1 = 0.0;
    if (std::fabs(b.z2) < 1.0e-20) b.z2 = 0.0;
}

