// ---- Spaces: convolution reverb ----
// Non-uniform partitioned FFT convolution (blocks of 64, 512 and 4096 samples) with no added latency.
// Twelve impulse responses are generated by code; a user impulse response can be loaded from a file.
class Spaces : public Plugin {
public:
    static constexpr int kBuiltIn = 12;                 // the impulse choice has one more entry: the user's file
    static constexpr double kMaxImpulseSeconds = 10.0;
    Spaces();
    ~Spaces() override;
    const char* typeId() const override { return "convolve"; }
    const char* displayName() const override { return "Spaces"; }
    void prepare(double sr) override;
    void process(ProcessContext& c) override;
    void reset() override;
    double tailSeconds() const override;
    Json saveExtra() const override;
    void loadExtra(const Json& j, const std::string& projectDir) override;
    std::vector<Preset> factoryPresets() const override;
    std::vector<ParamGroup> paramGroups() const override;

    // ---- control thread ----
    // Reads an audio file (mono or stereo, any rate; anything after 10 s is faded off), makes it the user
    // impulse and selects it. The file's energy is normalised so that every impulse plays at a similar level.
    bool loadImpulse(const std::string& path, std::string* error = nullptr);
    // The same from memory (not saved with the project unless the data carries a path). nullptr clears it.
    bool setImpulse(SamplePtr data, bool normalize = true, std::string* error = nullptr);
    std::string impulsePath() const;
    static const char* impulseName(int index);          // 0..kBuiltIn-1 built in, kBuiltIn = "User file"
    // The impulse response as it is convolved (engine rate, after normalising), for drawing and for tests.
    // index -1 = the one selected now. Null before prepare() and for an empty user slot.
    SamplePtr impulseData(int index = -1) const;

    Param *pImpulse, *pPre, *pDecay, *pLength, *pLowCut, *pHighCut, *pWidth, *pMix;

private:
    void rebuildUserLocked();
    void publishLocked();

    RtShared<space::Rig> rig_;
    std::atomic<uint32> gen_{0};
    // control threads, under ctl_
    mutable std::mutex ctl_;
    SamplePtr userSource_;
    std::string userPath_;
    bool userNormalize_ = true, prepared_ = false, userDirty_ = false;
    std::shared_ptr<const space::Kernel> userKernel_;
    // audio thread
    const space::Rig* rt_ = nullptr;
    const space::Kernel* kernel_ = nullptr;
    uint32 seenGen_ = 0;
    int active_ = -1, fadeOut_ = 0;
    dsp::DelayLine pre_[2];
    int preA_ = 0, preB_ = 0, preFade_ = 0;     // a pre-delay that moves is crossfaded to its new time
    dsp::Biquad lc_[2], hc_[2];
    float lcSeen_ = -1.0f, hcSeen_ = -1.0f;
    Ramp mix_, width_, fade_;
    bool primed_ = false, idle_ = true;
    int64 zeroRun_ = 0;
    double sr_ = 48000.0;
};

