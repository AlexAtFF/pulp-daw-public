#pragma once
// RIPPLE: a wavetable synth. Two oscillators that read band-limited wavetables and morph between
// neighbouring frames, each with up to seven unison voices; a sub oscillator and noise; a multimode
// filter; three envelopes and two LFOs, with the wavetable position as the main modulation target.
//
// A wavetable is a row of single-cycle frames of 2048 samples. Every frame is stored at ten levels
// with fewer and fewer harmonics (512, 256 ... 1: one level per octave), and a note reads the level
// whose harmonics still fit under the sample rate, so nothing audible aliases anywhere on the keyboard.
// Every level is stored at eight (the two lowest) or sixteen samples per cycle of its highest harmonic
// and read with a six-point interpolator, which keeps the images the interpolation itself makes far
// below the signal.
#include "pulp/Audio.h"
#include "pulp/Effects.h"
#include "pulp/Plugin.h"
#include "pulp/SynthParts.h"
#include "pulp/Trio.h"

namespace pulp {

class Ripple : public Instrument {
public:
    static constexpr int kFrameSize = 2048;
    static constexpr int kMips = 10;
    static constexpr int kMaxFrames = 256;
    static constexpr int kUnison = 7;
    static constexpr int kMaxPoly = 32;
    static constexpr int kSlots = kMaxPoly + 8;     // the extra ones hold voices that are fading out after being stolen

    struct Wavetable {
        std::string name;
        std::string path;           // where a user table came from ("" for the built-in ones)
        int frames = 0;
        std::vector<float> data;    // per level, per frame: two guard samples, the cycle, three guard samples
        size_t mipBase[kMips] = {};
        // Level m holds harmonics 1..(512 >> m), in a cycle of 4096, 2048, 2048, 1024, 512, 256 and then 128 samples.
        static int mipBits(int m) { return m <= 1 ? 12 - m : std::max(7, 13 - m); }
        static int mipSize(int m) { return 1 << mipBits(m); }
        static int mipHarmonics(int m) { return (kFrameSize / 4) >> m; }
        static constexpr int kGuard = 5;
        // Sample 0 of a frame at a level; [-2], [-1] and [size] .. [size + 2] wrap around, for interpolation.
        const float* frame(int mip, int f) const { return data.data() + mipBase[mip] + (size_t)f * (size_t)(mipSize(mip) + kGuard) + 2; }
    };
    using TablePtr = std::shared_ptr<const Wavetable>;

    Ripple();
    const char* typeId() const override { return "wavetable"; }
    const char* displayName() const override { return "Ripple"; }
    void prepare(double sampleRate) override;
    void reset() override;
    int activeVoices() const override { return voicesActive_.load(std::memory_order_relaxed); }
    double tailSeconds() const override;
    Json saveExtra() const override;
    void loadExtra(const Json& j, const std::string& projectDir) override;
    std::vector<Preset> factoryPresets() const override;
    std::vector<ParamGroup> paramGroups() const override;
    int readScope(float* dst, int n) const override { return scope_.read(dst, n); }

    // The wavetables that come with the synth, generated by code.
    static int numBuiltinTables();
    static const Wavetable& builtinTable(int index);
    static int userTableIndex() { return numBuiltinTables(); }      // the value of the table parameters that selects the user table

    // Builds a table from numFrames cycles of 2048 samples each, one after another. Not for the audio thread.
    static TablePtr makeTable(const float* cycles, int numFrames, const std::string& name);
    // Builds a table from audio: cycles of 2048 samples one after another, or (any other length) one single cycle.
    static TablePtr makeTable(const SampleData& audio, const std::string& name, std::string* error = nullptr);

    // Control thread. Reads a WAV (or FLAC / AIFF) file as the user wavetable. Notes that are sounding
    // carry on and cross-fade to the new table. On failure the current table stays and error says why.
    bool loadWavetable(const std::string& path, std::string* error = nullptr);
    void setWavetable(TablePtr table);      // null clears it; a table parameter set to "User table" then plays the first built-in one
    TablePtr wavetable() const;
    std::string wavetablePath() const;

    struct OscParams { Param *table, *pos, *coarse, *fine, *level, *pan, *uni, *detune, *spread, *phase, *posEnv, *posLfo[2], *posY; };
    OscParams osc[2];
    Param *pSubWave, *pSubOct, *pSubLevel, *pNoise, *pNoiseColor;
    Param *pFType, *pCutoff, *pReso, *pFEnv, *pFKey, *pFVel, *pFAttack, *pFDecay, *pFSustain, *pFRelease;
    Param *pAttack, *pDecay, *pSustain, *pRelease, *pVelSens;
    Param *pMAttack, *pMDecay, *pMSustain, *pMRelease, *pMEnvPitch;
    Param *pLfoWave[2], *pLfoRate[2], *pLfoDelay[2], *pLfoPitch[2], *pLfoCutoff[2], *pLfoAmp[2];
    Param *pVoices, *pGlide, *pVolume;
    Param *pChorus, *pChRate, *pChDepth, *pDelay, *pDTime, *pDFeed;

protected:
    void beginBlock(ProcessContext& ctx) override;
    void handleEvent(const NoteEvent& e, ProcessContext& ctx) override;
    void render(float* L, float* R, int n, ProcessContext& ctx) override;

private:
    // The user table as the audio thread sees it: the current one and the one before, so a voice can
    // cross-fade from the old to the new while both are guaranteed to be alive.
    struct UserSlot { TablePtr cur, prev; };

    struct OscSnap {
        int table = 0, uni = 1;
        float pos = 0.0f, ratio = 1.0f, level = 0.0f, phaseRand = 0.0f, posEnv = 0.0f, posLfo[2] = {0.0f, 0.0f}, posY = 0.0f;
        float uniRatio[kUnison] = {}, uniPan[kUnison] = {};
    };
    struct LfoSnap { int wave = 0; float rate = 1.0f, delay = 0.0f, pitch = 0.0f, cutoff = 0.0f, amp = 0.0f; };
    struct Snap {
        OscSnap osc[2];
        int subWave = 0, ftype = 0, voices = 16;
        float subRatio = 0.5f, subLevel = 0.0f, noise = 0.0f, noiseCoef = 1.0f;
        float cutoff = 20000.0f, k = 1.0f, fenv = 0.0f, fkey = 0.0f, fvel = 0.0f;
        float env[3][4] = {};       // amplitude, filter, modulation: attack, decay, sustain, release
        float menvPitch = 0.0f, glideMs = 0.0f, velSens = 1.0f;
        LfoSnap lfo[2];
    };
    struct OscVoice {
        uint32 phase[kUnison] = {}, inc[kUnison] = {};
        std::int32_t incStep[kUnison] = {};
        float gl[kUnison] = {}, glStep[kUnison] = {}, gr[kUnison] = {}, grStep[kUnison] = {};
        float pos = 0.0f, posStep = 0.0f;
        int run = 0, uni = 0;               // unison voices to render in this control period / in use
        int table = 0, mip = 0;
        uint32 serial = 0;                  // which user table this voice has caught up with
        bool xfade = false;                 // moving from another table or level over this control period
        int fromTable = 0, fromMip = 0;
        uint32 fromSerial = 0;
        float xf = 1.0f;
    };
    struct Voice {
        bool active = false, released = false;
        uint32 id = 0, age = 0;
        int key = 60, group = 0;
        float vel = 1.0f, pan = 0.0f, fine = 0.0f, modX = 0.5f, modY = 0.5f, relScale = 1.0f;
        float bend = 0.0f, bendTarget = 0.0f, bendStep = 0.0f;
        float kill = 1.0f, killStep = 0.0f;
        double time = 0.0;
        int ctlLeft = 0;
        float lfoPhase[2] = {0.0f, 0.0f}, lfoRnd[2] = {0.0f, 0.0f};
        dsp::Noise rng, noise;
        OscVoice osc[2];
        BlepOsc sub;
        float subDt = 0.0f, subDtStep = 0.0f, subG = 0.0f, subGStep = 0.0f;
        float noiseG = 0.0f, noiseGStep = 0.0f, noiseZ = 0.0f;
        parts::Env aenv, fenv, menv;        // the amplitude envelope runs per sample, the other two per control period
        parts::StereoSvf svf[2];
        float g = 1.0f, gStep = 0.0f, k = 1.0f, kStep = 0.0f;
        float outL = 0.0f, outLStep = 0.0f, outR = 0.0f, outRStep = 0.0f;
    };

    void startVoice(const NoteEvent& e);
    void control(Voice& v, bool snap);
    void renderVoice(Voice& v, float* L, float* R, int n);
    void renderOsc(OscVoice& o, float* L, float* R, int m);
    const Wavetable* resolve(int table, uint32 serial) const;

    RtShared<UserSlot> user_;
    mutable std::mutex pathM_;
    std::string path_;                      // the user table's path as given (kept even if the file was missing)
    const UserSlot* slot_ = nullptr;        // audio thread, valid for the current quantum
    const UserSlot* lastSlot_ = nullptr;
    uint32 slotSerial_ = 0;

    Snap snap_;
    Voice voices_[kSlots];
    uint32 ageCounter_ = 0;
    double sr_ = 48000.0, maxHz_ = 24000.0;
    float hostBend_ = 0.0f, lastKey_ = -1.0f;
    bool primed_ = false;
    // effects
    dsp::DelayLine chorus_[2], delay_[2];
    float chPhase_ = 0.0f, chRate_ = 0.5f, chDepth_ = 0.0f, dlTime_ = 0.0f, dlTarget_ = 0.0f, dlDamp_[2] = {0.0f, 0.0f}, dlDampCoef_ = 1.0f;
    Ramp chMix_, dlMix_, dlFeed_, volume_;
    ScopeTap scope_;
    std::atomic<int> voicesActive_{0};
};

} // namespace pulp
